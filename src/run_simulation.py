from src.data_generator import generate_dynamic_tape
from src.estimator_pipeline import FastCanonicalEstimators

def run_pipeline_benchmark(system_type: int):
    print(f"Running IEEE {system_type}-Bus Simulation...")
    sys_model = CanonicalIEEEGrid(system_type=system_type)
    tape = generate_dynamic_tape(sys_model, n_steps=250, seed=42)
    est = FastCanonicalEstimators(sys_model)

    _ = est.step_proposed_robust(tape["z_attack"][0], tape["f_meas"][0], tape["rocof_meas"][0])
    _ = est.step_badugu_2026(tape["z_attack"][0])
    est = FastCanonicalEstimators(sys_model)

    tve_lse, tve_bad, tve_prop = np.zeros(250), np.zeros(250), np.zeros(250)
    sp_bad, sp_prop = np.zeros(250), np.zeros(250)
    times_prop = np.zeros(250)

    for t in range(250):
        z_t, v_true, sp_true = tape["z_attack"][t], tape["v_true"][t], tape["true_spoof_deg"][t]

        _, v_lse = est.compute_pa_and_lse(z_t)
        v_b, sp_b_est = est.step_badugu_2026(z_t)

        t0 = time.perf_counter()
        v_p, sp_p_est = est.step_proposed_robust(z_t, tape["f_meas"][t], tape["rocof_meas"][t])
        times_prop[t] = (time.perf_counter() - t0) * 1000.0

        tve_lse[t]  = np.max(np.abs(v_lse - v_true) / np.abs(v_true)) * 100.0
        tve_bad[t]  = np.max(np.abs(v_b - v_true) / np.abs(v_true)) * 100.0
        tve_prop[t] = np.max(np.abs(v_p - v_true) / np.abs(v_true)) * 100.0
        sp_bad[t]   = np.max(np.abs(sp_b_est - sp_true))
        sp_prop[t]  = np.max(np.abs(sp_p_est - sp_true))

    return tve_lse, tve_bad, tve_prop, sp_bad, sp_prop, times_prop

